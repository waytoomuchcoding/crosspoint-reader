#!/usr/bin/env python3
"""Generate compact GB18030/GBK/GB2312 and Big5/CP950 lookup tables for Flash (.rodata)."""

from pathlib import Path
import sys


def build_gbk_2byte_table():
    entries = []
    for b1 in range(0x81, 0xFF):
        for b2 in range(0x40, 0xFF):
            if b2 == 0x7F:
                continue
            raw = bytes([b1, b2])
            cp = 0xFFFD
            for codec in ("gb18030", "gbk"):
                try:
                    s = raw.decode(codec)
                    if len(s) == 1 and ord(s) <= 0xFFFF:
                        cp = ord(s)
                        break
                except UnicodeDecodeError:
                    pass
            entries.append(cp)
    assert len(entries) == 126 * 190
    return entries


def build_gb18030_4byte_bmp_runs():
    runs = []
    last_p = None
    last_cp = None
    run_start_p = None
    run_start_cp = None
    run_len = 0
    for p in range(39420):
        t = p
        b4 = 0x30 + (t % 10)
        t //= 10
        b3 = 0x81 + (t % 126)
        t //= 126
        b2 = 0x30 + (t % 10)
        t //= 10
        b1 = 0x81 + t
        cp = ord(bytes([b1, b2, b3, b4]).decode("gb18030"))
        if last_p is not None and p == last_p + 1 and cp == last_cp + 1:
            run_len += 1
        else:
            if run_start_p is not None:
                runs.append((run_start_p, run_start_cp, run_len))
            run_start_p = p
            run_start_cp = cp
            run_len = 1
        last_p = p
        last_cp = cp
    if run_start_p is not None:
        runs.append((run_start_p, run_start_cp, run_len))
    assert sum(r[2] for r in runs) == 39420
    return runs


def build_big5_2byte_table():
    entries = []
    for b1 in range(0xA1, 0xFA):
        for b2 in list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF)):
            raw = bytes([b1, b2])
            cp = 0xFFFD
            for codec in ("cp950", "big5", "big5hkscs"):
                try:
                    s = raw.decode(codec)
                    if len(s) == 1 and ord(s) <= 0xFFFF:
                        cp = ord(s)
                        break
                except UnicodeDecodeError:
                    pass
            entries.append(cp)
    assert len(entries) == 89 * 157
    return entries


def format_u16_array(entries, per_line=12):
    lines = []
    for i in range(0, len(entries), per_line):
        chunk = entries[i : i + per_line]
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in chunk) + ",")
    return "\n".join(lines)


def main():
    out_path = Path(
        sys.argv[1]
        if len(sys.argv) > 1
        else Path(__file__).resolve().parent.parent / "lib" / "TextEncoding" / "CjkEncodingTables.h"
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)

    gbk_entries = build_gbk_2byte_table()
    gb18030_runs = build_gb18030_4byte_bmp_runs()
    big5_entries = build_big5_2byte_table()

    run_lines = []
    for i in range(0, len(gb18030_runs), 6):
        chunk = gb18030_runs[i : i + 6]
        run_lines.append("    " + ", ".join(f"{{{p}u, 0x{cp:04X}u}}" for p, cp, _ in chunk) + ",")

    content = f"""// Auto-generated by scripts/gen_cjk_encodings.py — DO NOT EDIT MANUALLY.
#pragma once

#include <cstddef>
#include <cstdint>

namespace textencoding::tables {{

struct Gb18030BmpRun {{
  uint16_t startPointer;
  uint16_t startCodepoint;
}};

// GBK / GB18030 2-byte table: lead 0x81..0xFE (126) x trail 0x40..0xFE except 0x7F (190) = 23,940 entries.
inline constexpr size_t kGbk2ByteCount = {len(gbk_entries)};
inline constexpr uint16_t kGbk2ByteToUcs2[kGbk2ByteCount] = {{
{format_u16_array(gbk_entries)}
}};

// GB18030 4-byte BMP contiguous pointer runs covering pointers 0..39419 (lead 0x81..0x84).
inline constexpr size_t kGb18030BmpRunCount = {len(gb18030_runs)};
inline constexpr Gb18030BmpRun kGb18030BmpRuns[kGb18030BmpRunCount] = {{
{chr(10).join(run_lines)}
}};

// Big5 / CP950 2-byte table: lead 0xA1..0xF9 (89) x trail 0x40..0x7E, 0xA1..0xFE (157) = 13,973 entries.
inline constexpr size_t kBig52ByteCount = {len(big5_entries)};
inline constexpr uint16_t kBig52ByteToUcs2[kBig52ByteCount] = {{
{format_u16_array(big5_entries)}
}};

}}  // namespace textencoding::tables
"""
    out_path.write_text(content, encoding="utf-8")
    print(f"Wrote {out_path} ({len(content)} bytes)")


if __name__ == "__main__":
    main()
