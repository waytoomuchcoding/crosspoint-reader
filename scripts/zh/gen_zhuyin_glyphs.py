#!/usr/bin/env python3
"""Generate lib/ZhDict/ZhuyinGlyphs.h from Ark Pixel Font 10 px bopomofo designs.

Input: the PNGs in assets/glyphs/10/cmap/common/3100-312F Bopomofo of
https://github.com/TakWolf/ark-pixel-font (SIL Open Font License 1.1).
Each 10x10 design is cropped to its 9x9 drawing area (rows 1-9, columns 0-8).

Usage: python3 scripts/zh/gen_zhuyin_glyphs.py ARK_BOPOMOFO_DIR
"""

import os
import sys

from PIL import Image

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "lib", "ZhDict", "ZhuyinGlyphs.h")
FIRST, LAST = 0x3105, 0x3129  # ㄅ..ㄩ, the 37 standard symbols


def main():
    src = sys.argv[1]
    rows_out = []
    for cp in range(FIRST, LAST + 1):
        im = Image.open(os.path.join(src, f"{cp:04X}.png")).convert("RGBA").getchannel("A")
        rows = []
        for y in range(1, 10):
            v = 0
            for x in range(9):
                v = (v << 1) | (1 if im.getpixel((x, y)) > 127 else 0)
            rows.append(v)
        rows_out.append((cp, rows))

    with open(OUT, "w") as f:
        f.write("#pragma once\n// Generated by scripts/zh/gen_zhuyin_glyphs.py. Do not edit.\n")
        f.write("// Bopomofo glyphs from Ark Pixel Font 10px (SIL Open Font License 1.1),\n")
        f.write("// https://github.com/TakWolf/ark-pixel-font. Each glyph is 9 rows of 9 bits,\n")
        f.write("// most significant of the 9 bits = leftmost pixel.\n\n#include <cstdint>\n\n")
        f.write("namespace zh {\n\n")
        f.write(f"constexpr uint32_t ZHUYIN_FIRST_CP = 0x{FIRST:04X};\n")
        f.write(f"constexpr int ZHUYIN_GLYPH_COUNT = {LAST - FIRST + 1};\n\n")
        f.write("constexpr uint16_t ZHUYIN_GLYPHS[ZHUYIN_GLYPH_COUNT][9] = {\n")
        for cp, rows in rows_out:
            f.write("    {" + ", ".join(f"0x{r:03X}" for r in rows) + f"}},  // {chr(cp)}\n")
        f.write("};\n\n}  // namespace zh\n")
    print(OUT)


if __name__ == "__main__":
    main()
