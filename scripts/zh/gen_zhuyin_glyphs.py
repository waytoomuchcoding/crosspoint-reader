#!/usr/bin/env python3
"""Generate lib/ZhDict/ZhuyinGlyphs.h: bopomofo glyph sets for zhuyin ruby.

Three sets, so ruby can follow the text size (lib/ZhDict/ZhDictImpl.h picks one
and an integer scale from the line height):
  5x7   Fusion Pixel Font 8px   (drawing area rows 1-7, columns 1-5)
  9x9   Ark Pixel Font 10px     (design PNGs, rows 1-9, columns 0-8)
  11x11 Ark Pixel Font 12px     (drawing area rows 1-11, columns 0-10)
All SIL Open Font License 1.1, https://github.com/TakWolf/ark-pixel-font and
https://github.com/TakWolf/fusion-pixel-font.

Inputs:
  ARK_BOPOMOFO_DIR  assets/glyphs/10/cmap/common/3100-312F Bopomofo of ark-pixel-font
  FUSION_8PX_OTF    fusion-pixel-8px-monospaced-zh_tw.otf (release zip)
  ARK_12PX_OTF      ark-pixel-12px-monospaced-zh_tw.otf (release zip)

Usage: python3 scripts/zh/gen_zhuyin_glyphs.py ARK_BOPOMOFO_DIR FUSION_8PX_OTF ARK_12PX_OTF
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "lib", "ZhDict", "ZhuyinGlyphs.h")
FIRST, LAST = 0x3105, 0x3129  # ㄅ..ㄩ, the 37 standard symbols


def bits(img, x0, y0, w, h):
    rows = []
    for y in range(y0, y0 + h):
        v = 0
        for x in range(x0, x0 + w):
            v = (v << 1) | (1 if img.getpixel((x, y)) > 127 else 0)
        rows.append(v)
    return rows


def from_pngs(src):
    out = []
    for cp in range(FIRST, LAST + 1):
        im = Image.open(os.path.join(src, f"{cp:04X}.png")).convert("RGBA").getchannel("A")
        out.append(bits(im, 0, 1, 9, 9))
    return out


def from_otf(path, px, x0, y0, w, h):
    font = ImageFont.truetype(path, px)
    out = []
    for cp in range(FIRST, LAST + 1):
        im = Image.new("L", (px, px), 0)
        ImageDraw.Draw(im).text((0, 0), chr(cp), font=font, fill=255)
        # Nothing may fall outside the drawing area.
        full = im.point(lambda v: 255 if v > 127 else 0).getbbox()
        if full and (full[0] < x0 or full[1] < y0 or full[2] > x0 + w or full[3] > y0 + h):
            sys.exit(f"{chr(cp)} in {path} exceeds its {w}x{h} drawing area: {full}")
        out.append(bits(im, x0, y0, w, h))
    return out


def write_set(f, name, w, h, glyphs):
    digits = (w + 3) // 4
    f.write(f"constexpr uint16_t {name}[ZHUYIN_GLYPH_COUNT][{h}] = {{\n")
    for i, rows in enumerate(glyphs):
        f.write("    {" + ", ".join(f"0x{r:0{digits}X}" for r in rows) + f"}},  // {chr(FIRST + i)}\n")
    f.write("};\n\n")


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    sets = [
        ("ZHUYIN_GLYPHS_5X7", 5, 7, from_otf(sys.argv[2], 8, 1, 1, 5, 7)),
        ("ZHUYIN_GLYPHS_9X9", 9, 9, from_pngs(sys.argv[1])),
        ("ZHUYIN_GLYPHS_11X11", 11, 11, from_otf(sys.argv[3], 12, 0, 1, 11, 11)),
    ]
    with open(OUT, "w") as f:
        f.write("#pragma once\n// Generated by scripts/zh/gen_zhuyin_glyphs.py. Do not edit.\n")
        f.write("// Bopomofo glyphs from Fusion Pixel Font 8px (5x7), Ark Pixel Font 10px (9x9)\n")
        f.write("// and Ark Pixel Font 12px (11x11), SIL Open Font License 1.1,\n")
        f.write("// https://github.com/TakWolf/ark-pixel-font. Each glyph is one value per row,\n")
        f.write("// most significant of the row's bits = leftmost pixel.\n\n#include <cstdint>\n\n")
        f.write("namespace zh {\n\n")
        f.write(f"constexpr uint32_t ZHUYIN_FIRST_CP = 0x{FIRST:04X};\n")
        f.write(f"constexpr int ZHUYIN_GLYPH_COUNT = {LAST - FIRST + 1};\n\n")
        for name, w, h, glyphs in sets:
            write_set(f, name, w, h, glyphs)
        f.write("}  // namespace zh\n")
    print(OUT)


if __name__ == "__main__":
    main()
