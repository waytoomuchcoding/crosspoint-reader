ShibaPose getCurrentPose() { return gCurrentPose; }

void setCurrentPose(const ShibaPose pose) {
  if (static_cast<uint8_t>(pose) < static_cast<uint8_t>(ShibaPose::Count)) {
    gCurrentPose = pose;
  }
}

ShibaPose advancePoseCycle() {
  const uint8_t next =
      static_cast<uint8_t>((static_cast<uint8_t>(gCurrentPose) + 1U) % static_cast<uint8_t>(ShibaPose::Count));
  gCurrentPose = static_cast<ShibaPose>(next);
  return gCurrentPose;
}

void stampShibaOnLedge(const GfxRenderer& renderer, const int shibaX, const int ledgeY, const ShibaPose pose) {
  const uint8_t* ink = SHIBA_LOAF_SLEEP_INK;
  const uint8_t* mask = SHIBA_LOAF_SLEEP_MASK;
  switch (pose) {
    case ShibaPose::LoafSleep:
      ink = SHIBA_LOAF_SLEEP_INK;
      mask = SHIBA_LOAF_SLEEP_MASK;
      break;
    case ShibaPose::LoafAwake:
      ink = SHIBA_LOAF_AWAKE_INK;
      mask = SHIBA_LOAF_AWAKE_MASK;
      break;
    case ShibaPose::CurledCroissant:
      ink = SHIBA_CURLED_CROISSANT_INK;
      mask = SHIBA_CURLED_CROISSANT_MASK;
      break;
    case ShibaPose::ChinOnPaws:
    case ShibaPose::Count:
      ink = SHIBA_CHIN_ON_PAWS_INK;
      mask = SHIBA_CHIN_ON_PAWS_MASK;
      break;
  }
  blitMaskedSprite(renderer, shibaX, ledgeY - SHIBA_LEDGE_OFFSET_Y, SHIBA_SPRITE_W, SHIBA_SPRITE_H, ink, mask);
}

void stampMugOnLedge(const GfxRenderer& renderer, const int cupX, const int ledgeY) {
  blitMaskedSprite(renderer, cupX - 2, ledgeY - SHIBA_MUG_LEDGE_OFFSET_Y, SHIBA_MUG_W, SHIBA_MUG_H, SHIBA_MUG_36X35_INK,
                   SHIBA_MUG_36X35_MASK);
}

void drawIcon(const GfxRenderer& renderer, const ShibaIcon icon, const int x, const int y, const bool black) {
  const IconSpec spec = getIconSpec(icon);
  blitIconBits(renderer, x, y, spec.width, spec.height, spec.bits, black);
}

int getIconWidth(const ShibaIcon icon) { return getIconSpec(icon).width; }

int getIconHeight(const ShibaIcon icon) { return getIconSpec(icon).height; }

