void blitMaskedSprite(const GfxRenderer& renderer, const int x0, const int y0, const int width, const int height,
                      const uint8_t* inkBits, const uint8_t* maskBits) {
  const int stride = (width + 7) / 8;
  for (int row = 0; row < height; ++row) {
    const int rowOffset = row * stride;
    for (int col = 0; col < width; ++col) {
      const uint8_t bitMask = static_cast<uint8_t>(1U << (7 - (col & 7)));
      const int byteIdx = rowOffset + (col >> 3);
      if ((maskBits[byteIdx] & bitMask) != 0) {
        const bool isBlack = (inkBits[byteIdx] & bitMask) != 0;
        renderer.drawPixel(x0 + col, y0 + row, isBlack);
      }
    }
  }
}

void blitIconBits(const GfxRenderer& renderer, const int x0, const int y0, const int width, const int height,
                  const uint8_t* bits, const bool black) {
  const int stride = (width + 7) / 8;
  for (int row = 0; row < height; ++row) {
    const int rowOffset = row * stride;
    for (int col = 0; col < width; ++col) {
      const uint8_t bitMask = static_cast<uint8_t>(1U << (7 - (col & 7)));
      if ((bits[rowOffset + (col >> 3)] & bitMask) != 0) {
        renderer.drawPixel(x0 + col, y0 + row, black);
      }
    }
  }
}

